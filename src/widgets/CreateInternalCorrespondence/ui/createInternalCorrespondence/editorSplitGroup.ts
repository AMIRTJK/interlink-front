// Счётчик групп автоматически разрезанных блоков. Части одной группы носят
// общий идентификатор в AUTOSPLIT_ATTR и склеиваются обратно при сохранении,
// поэтому последовательность обязана быть одна на весь редактор: и пагинация,
// и ручной разрез по Enter берут идентификаторы отсюда.
let splitGroupSeq = 0;

export const nextSplitGroupId = (): string => `g${++splitGroupSeq}`;
