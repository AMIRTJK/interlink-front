import { useEffect } from "react";
import { ChatApp } from "./ChatApp";
import { useChat } from "../lib/ChatContext";

// ─── Чат как полноценный раздел системы ───────────────────────────────────────
// Монтируется на маршруте AppRoutes.CHAT. Навигация системы остаётся на месте
// (шапка/боковое меню — как в остальных модулях, вкладка «Чат» подсвечена), а сам
// чат занимает всю площадь под ней, край в край — без компактного окна и полей
// (полноэкранную раскладку под чат готовит MainLayout). Всплывающее окно быстрого
// доступа здесь не нужно — закрываем его при входе, чтобы чат не дублировался.

export const ChatPage = () => {
  const { closeChat } = useChat();

  useEffect(() => {
    closeChat();
  }, [closeChat]);

  return <ChatApp variant="page" />;
};
